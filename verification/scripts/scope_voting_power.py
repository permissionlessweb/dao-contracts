#!/usr/bin/env python3
"""Write verification/SCOPE.md from Trailmark callers of the voting-power sinks."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "SCOPE.md"

ROOTS = [
    "packages/dao-voting",
    "packages/dao-interface",
    "contracts/proposal/dao-proposal-single",
    "contracts/proposal/dao-proposal-multiple",
    "contracts/proposal/dao-proposal-condorcet",
    "contracts/voting/dao-voting-cw4",
    "contracts/voting/dao-voting-cw20-staked",
    "contracts/voting/dao-voting-cw721-staked",
    "contracts/voting/dao-voting-cw721-roles",
    "contracts/voting/dao-voting-token-staked",
    "contracts/voting/dao-voting-zk",
    "contracts/test/dao-voting-cw20-balance",
    "contracts/delegation/dao-vote-delegation",
]

SINKS = [
    "compare_vote_count",
    "does_vote_count_pass",
    "does_vote_count_fail",
    "add_vote",
    "remove_vote",
    "get_voting_power_with_delegation",
    "query_is_active",
    "query_voting_power_at_height",
    "query_total_power_at_height",
]

PROPERTIES = {
    "compare_vote_count": "V1",
    "does_vote_count_pass": "V2 V3 V4",
    "does_vote_count_fail": "V2 V3 V4",
    "add_vote": "V5",
    "remove_vote": "V5",
    "get_voting_power_with_delegation": "V7",
    "query_is_active": "V6",
    "query_voting_power_at_height": "identity",
    "query_total_power_at_height": "identity",
}

ENTRIES = ("instantiate", "execute", "query", "reply", "migrate")


def _name(node: dict) -> str:
    for key in ("name", "qualified_name", "id"):
        value = node.get(key)
        if isinstance(value, str) and value:
            return value
    return ""


def _repo_relative(path: str) -> str:
    if not path:
        return ""
    candidate = Path(path)
    try:
        resolved = candidate.resolve()
    except OSError:
        resolved = candidate
    try:
        return resolved.relative_to(ROOT).as_posix()
    except ValueError:
        return candidate.name


def _loc(node: dict) -> str:
    loc = node.get("location") or {}
    path = loc.get("file_path") or node.get("file_path") or ""
    line = loc.get("start_line") or node.get("start_line") or ""
    path = _repo_relative(str(path))
    if path and line:
        return f"{path}:{line}"
    return path or str(node.get("id") or "")


def main() -> int:
    from trailmark.query.api import QueryEngine

    rows: list[str] = []
    seen: set[tuple[str, str, str]] = set()
    for rel in ROOTS:
        directory = ROOT / rel
        if not directory.exists():
            rows.append(f"| (missing) | | {rel} | | assumed | directory not in this checkout |")
            continue
        engine = QueryEngine.from_directory(str(directory), language="rust")
        try:
            engine.preanalysis()
        except Exception as exc:  # pragma: no cover - parser differences
            detail = str(exc).replace(str(ROOT) + "/", "")
            rows.append(f"| (preanalysis) | | {rel} | | assumed | {detail} |")
        for sink in SINKS:
            callers = engine.callers_of(sink) or []
            for caller in callers:
                if isinstance(caller, str):
                    name, loc = caller, ""
                else:
                    name, loc = _name(caller), _loc(caller)
                key = (name, sink, loc or rel)
                if key in seen:
                    continue
                seen.add(key)
                status = "identity" if PROPERTIES[sink] == "identity" else "proved"
                if sink == "query_is_active":
                    status = "proved"
                rows.append(
                    f"| {name} | {sink} | {PROPERTIES[sink]} | {loc} | {status} | "
                    "declared entry if the function is instantiate/execute/query/reply/migrate |"
                )

    header = """# Voting-power scope

Generated by `verification/scripts/scope_voting_power.py` with Trailmark.
Regenerate after a change under `packages/dao-voting` or `contracts/proposal`.
A new caller of `compare_vote_count` needs a status in this file.

`proved` means the callee is one of V1–V7 in `verification/lean/VotingPow.lean`.
`identity` means the query returns a stored integer widened to `Uint256`.
`assumed` means a scanned directory is missing or Trailmark preanalysis failed.

CosmWasm `#[entry_point]` is a macro Trailmark does not expand. Functions named
instantiate, execute, query, reply, or migrate are the untrusted entries.
"""
    body = "\n".join(
        [
            "| Caller | Sink | Property | Location | Status | Note |",
            "|---|---|---|---|---|---|",
            *rows,
            "",
            "Entry names watched: " + ", ".join(ENTRIES) + ".",
            "",
        ]
    )
    OUT.write_text(header + "\n" + body)
    print(f"wrote {OUT} ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
